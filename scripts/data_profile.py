def classify(note: str) -> str:
    n = note.lower()
    for name, pat in CATS:
        if name == "process pending" and re.search(r"\bserved\b", n) and "return of" not in n:
            continue  # "summons served" / "notice served": process is done, not pending
        if re.search(pat, n):
            return name
    return "other"


