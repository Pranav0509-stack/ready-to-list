def md(df: pd.DataFrame, index: bool = False, floatfmt: str = ".2f") -> str:
    return df.to_markdown(index=index, floatfmt=floatfmt)


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def col_table(df: pd.DataFrame, meanings: dict[str, str]) -> str:
    rows = []
    for c in df.columns:
        s = df[c]
        if pd.api.types.is_numeric_dtype(s):
            stat = f"min {s.min():g}, median {s.median():g}, mean {s.mean():.2f}, max {s.max():g}"
        else:
            vc = s.value_counts()
            top = ", ".join(f"{str(k)[:28]} ({v})" for k, v in vc.head(3).items())
            stat = f"{s.nunique()} unique, {s.isna().sum()} null; top: {top}"
        rows.append({"column": c, "dtype": str(s.dtype), "meaning": meanings.get(c, ""), "key stats": stat})
    return md(pd.DataFrame(rows))


