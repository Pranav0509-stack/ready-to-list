def parse(text: str) -> dict:
    lines = str(text).split("\n")
    present, absent, order = [], [], []
    for ln in lines:
        if ln.startswith("Present:"):
            present = [x.strip() for x in ln[8:].split(",") if x.strip()]
        elif ln.startswith("Absent:"):
            absent = [x.strip() for x in ln[7:].split(",") if x.strip()]
        else:
            order.append(ln)
    return {"present": present, "absent": absent, "order": " ".join(order).strip()}


